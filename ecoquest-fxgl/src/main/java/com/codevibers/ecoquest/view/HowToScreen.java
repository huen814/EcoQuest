package com.codevibers.ecoquest.view;

import java.util.List;

import com.codevibers.ecoquest.EcoQuestApp;
import com.codevibers.ecoquest.model.Sfx;

public final class HowToScreen extends Screen {
    private final DialogBox box = new DialogBox(6, Ui.H - 150, Ui.W - 12, 144);

    public HowToScreen(EcoQuestApp app) {
        super(app);
        root.getChildren().addAll(Sprites.view("backdrop/title.png"), box);
    }

    @Override
    public void enter() {
        box.show(List.of(
                "WALK WITH ARROWS OR WASD. PRESS E, Z OR ENTER (A) TO PICK UP LITTER OR DROP IT INTO THE BIN YOU FACE.",
                "RIGHT BIN: +10 SCORE AND POLLUTION -5. WRONG BIN: -5 AND YOUR COMBO RESETS. CHAIN SORTS FOR UP TO x4.",
                "SEEDS GO INTO EMPTY PLANTING SPOTS: +20 AND A GROWING TREE. RIVER ITEMS ARE WORTH +25: ROW THE BOAT WITH B.",
                "SPACE EMPTIES A FULL BIN. ECO BOOST STARS GIVE x2 SCORE. LEFT-OVER GARBAGE RAISES POLLUTION: AT 100% YOU LOSE!",
                "FINISH THE MISSION AND REACH THE TARGET SCORE. 3 STARS NEED POLLUTION UNDER 25% AND 2 OR FEWER MISTAKES. P OR ESC PAUSES, M MUTES. SETTINGS ARE IN THE MAIN MENU AND THE PAUSE MENU.",
                "SORTING EARNS COINS. SPEND THEM IN THE COSMETICS SHOP TO BUY AND WEAR NEW OUTFITS.",
                "GAME MODES: TIME ATTACK (90 SECONDS), ENDLESS SURVIVAL, CHAOS MODE (BINS KEEP SWAPPING), SPEED SORT (25 ITEMS, FASTEST TIME WINS) AND ZEN GARDEN (NO PRESSURE). FINISHING PAYS A SET COIN REWARD AND KEEPS YOUR BEST RECORD.",
                "BOSS FIGHTS: A BOSS WAITS AFTER LEVELS 3, 6 AND 10. MOVE IN EIGHT DIRECTIONS WITH ARROWS OR WASD AND HOLD LEFT-CLICK OR ENTER/Z TO FIRE THE SPIRIT BOTTLE. YOU AIM WITH THE MOUSE, OR SHOTS LOCK ONTO THE BOSS IF AUTO AIM IS ON (SETTINGS > CONTROLS). YOU HAVE 3 HEARTS: DODGE EVERY SHOT! AFTER A LOSS, ENTER TRIES AGAIN AND X QUITS.",
                "BOSSES GET FASTER AND MEANER AT HALF HEALTH. FAINT SLIME PUDDLES ARE SAFE UNTIL THEY TURN SOLID. THE FINAL BOSS, QUEEN BIJOU, THROWS RICOCHETING BOTTLE CAPS, RUSTY PIPES, ROLLING TIRES, LEAKY BATTERIES AND STINK BAGS. WATCH FOR THE WARNING BEFORE EACH ATTACK.",
                "THE ESCAPE: RUN FOR THE EXIT AND LOOP AROUND THE JUNK CUBES TO SHAKE HIM OFF. ENTER OR Z THROWS THE BOTTLE: IT STUNS HIM AND POPS GHOSTS. STINK CLOUDS SLOW YOU DOWN, AND HE WARNS YOU BEFORE HE LUNGES.",
                "BOSS REPLAY (IN GAME MODES) LETS YOU REFIGHT ANY BOSS YOU HAVE BEATEN FOR COINS AND A BEST-TIME RECORD. A NEW RECORD EARNS A ONE-TIME BONUS.",
                "CLEARING STORY LEVELS EARNS XP. EACH LEVEL-UP OFFERS A CHOICE OF ATTRIBUTES. PICK ONE TO SHAPE YOUR BUILD. CLEARING A STORY LEVEL FOR THE FIRST TIME ALWAYS LEVELS YOU UP. SEE YOURS FROM THE MAIN MENU, THE PAUSE MENU, OR BY PRESSING SPACE ON THE LEVEL SELECT."));
    }

    @Override
    public void update(double tpf) { box.update(tpf); }

    @Override
    public void onConfirm() {
        app.sfx(Sfx.SELECT);
        if (box.advance()) app.showMainMenu();
    }

    @Override
    public void onCancel() { app.showMainMenu(); }

    /** The title song keeps playing on this screen. */
    @Override
    public boolean titleMusic() { return true; }
}
